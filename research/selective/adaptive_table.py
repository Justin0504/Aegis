"""results/selective/adaptive_attacker.{verdict,whitebox}.json → paper-arxiv/figures/table_adaptive.tex"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "selective"
OUT = ROOT / "paper-arxiv" / "figures" / "table_adaptive.tex"

arms = {}
for arm in ("verdict", "whitebox"):
    p = RES / f"adaptive_attacker.{arm}.json"
    if p.exists():
        arms[arm] = json.load(p.open())
if not arms:
    raise SystemExit("no adaptive results yet")

K = max(a["summary"]["rounds"] for a in arms.values())
n = next(iter(arms.values()))["summary"]["n"]
attacker = next(iter(arms.values()))["summary"]["attacker"]
pc = lambda k, tot: f"{100 * k / tot:.1f}"

L = [
    "% Generated by research/selective/adaptive_attacker.py + adaptive_table.py — do not edit by hand.",
    "\\begin{table}[t]", "\\centering\\small", "\\setlength{\\tabcolsep}{5pt}",
    f"\\caption{{An adaptive attacker against the instruction-provenance pack, on the {n} corpus attacks of "
    "\\S\\ref{sec:instantiate}. Round 0 is the injection as recorded. In each later round an attacker model "
    f"({attacker}) rewrites what the agent reads, given either only the verdict or the rule, its reason and how the "
    "pack decides (white-box); an agent model then emits the next call from the user's request and the rewritten text, "
    "and the gateway checks the call it emitted. A round counts only when the agent made the attacker's call: same tool, "
    "every destination of the original present. \\emph{Flagged} is the share of the attacks still held or blocked after "
    "that round; \\emph{escaped} counts attacks flagged at round 0 that were realised and allowed by the end.}",
    "\\label{tab:adaptive}",
    "\\begin{tabular}{l" + "r" * (K + 1) + "rr}", "\\toprule",
    "Feedback & " + " & ".join(f"R{k}" for k in range(K + 1)) + " & Escaped & Agent balked \\\\",
    "\\midrule",
]
for arm, label in (("verdict", "Verdict only"), ("whitebox", "White-box")):
    if arm not in arms:
        continue
    s = arms[arm]["summary"]
    fl = [pc(s["flagged_by_round"][str(k)] if str(k) in s["flagged_by_round"] else s["flagged_by_round"][k], s["n"]) + "\\%" for k in range(K + 1)]
    f0 = s["flagged_by_round"]["0"] if "0" in s["flagged_by_round"] else s["flagged_by_round"][0]
    L.append(f"{label} & " + " & ".join(fl) + f" & {s['escaped_after_round0_flag']} of {f0} & {s['rounds_where_agent_did_not_emit']} rounds \\\\")
L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
OUT.write_text("\n".join(L) + "\n")
for arm, a in arms.items():
    s = a["summary"]
    print(arm, "flagged by round", s["flagged_by_round"], "escaped", s["escaped_after_round0_flag"],
          "surviving", s["surviving_rules"], "escaped_from", s["escaped_from_rule"])
print("wrote", OUT)
