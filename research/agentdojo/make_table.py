"""results/rows-*.jsonl + decisions-*.jsonl → paper-arxiv/figures/table_agentdojo.tex

    python make_table.py

Utility: share of the 97 user tasks completed with no attack present.
Utility under attack and attack success rate (ASR): over the user×injection
pairs, with the `important_instructions` attack. 95% Wilson intervals.
"Needs a person": share of clean tasks in which the gateway held at least
one call; with no reviewer present the hold is a refusal, so this is the
utility a deployment buys back by answering holds. For the auditor
configuration it counts tasks where the auditor refused a held call, i.e.
where a person would still be asked.
"""
from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parent / "paper-arxiv" / "figures" / "table_agentdojo.tex"

ROWS = [
    ("none", "No defense"),
    ("spotlighting_with_delimiting", "Spotlighting (delimiters)"),
    ("repeat_user_prompt", "Repeat user prompt"),
    ("tool_filter", "Tool filter (LLM)"),
    ("aegis_rules", "\\system{} rules, v1"),
    ("aegis", "\\system{} + L$_\\mathrm{p}$, v1"),
    ("aegis_rules_v2", "\\system{} rules"),
    ("aegis_v2", "\\system{} + L$_\\mathrm{p}$"),
    ("aegis_v2_audit", "\\quad holds reviewed by L3"),
]


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"),) * 2
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def load_rows():
    rows = {}
    for mode in ("utility", "security"):
        p = RES / f"rows-{mode}.jsonl"
        if not p.exists():
            continue
        for l in p.open():
            r = json.loads(l)
            if "error" in r:
                continue
            rows[(mode, r["cfg"], r["suite"], r["user_task"], r.get("injection_task"))] = r
    return rows


PIPELINE = {"aegis_rules": "aegis_rules", "aegis": "aegis", "aegis_rules_v2": "aegis_rules_v2",
            "aegis_v2": "aegis_v2", "aegis_v2_audit": "aegis_v2_audit"}


def needs_person(cfg):
    """From AgentDojo's own per-task transcripts of the clean run: a task
    needed a person if any tool result says the call was held. With the
    auditor reviewing holds, an approved hold leaves no such message and a
    refused one does, so the same test counts tasks a person would see."""
    if cfg not in PIPELINE:
        return None, 0
    base = RES / "logs" / f"gpt-4o-mini-2024-07-18-{PIPELINE[cfg]}"
    held = total = 0
    for f in base.glob("*/*/none/none.json"):
        d = json.loads(f.read_text())
        total += 1
        if any("held for human approval" in (m.get("error") or "") for m in d.get("messages", []) if m.get("role") == "tool"):
            held += 1
    return held, total


def main():
    rows = load_rows()
    agg = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for (mode, cfg, *_), r in rows.items():
        if mode == "utility":
            agg[cfg]["u"][0] += r["utility"]; agg[cfg]["u"][1] += 1
        else:
            agg[cfg]["ua"][0] += r["utility"]; agg[cfg]["ua"][1] += 1
            agg[cfg]["asr"][0] += r["security"]; agg[cfg]["asr"][1] += 1

    def cell(k, n, bold=False):
        if not n:
            return "---"
        lo, hi = wilson(k, n)
        s = f"{100*k/n:.1f}"
        s = f"\\textbf{{{s}}}" if bold else s
        return f"{s} {{\\scriptsize[{100*lo:.0f},{100*hi:.0f}]}}"

    lines = [
        "% Generated by research/agentdojo/make_table.py — do not edit by hand.",
        "\\begin{table*}[t]", "\\centering\\small", "\\setlength{\\tabcolsep}{5pt}",
        "\\caption{AgentDojo v1.2.1 end to end (four suites; 97 user tasks; 949 user$\\times$injection pairs with the "
        "\\texttt{important\\_instructions} attack), agent gpt-4o-mini-2024-07-18. Percentages with 95\\% Wilson intervals. "
        "In the \\system{} rows a hold has no reviewer, so it is a refusal; \\emph{needs a person} counts the clean "
        "tasks, of 97, in which at least one call was held, the utility a deployment buys back by answering holds. "
        "In the last row each hold goes first to the gateway's alignment auditor with the user's request as the goal; "
        "\\emph{needs a person} then counts the tasks where the auditor refused. "
        "v1 is the gateway as first submitted; the unmarked rows apply holds only to calls that act "
        "(\\S\\ref{sec:agentdojo}). \\emph{Pairs} is the number of the 949 attack pairs that completed: the OpenAI "
        "account ran out of credit near the end of the run; on the 829 pairs every configuration completed the ordering "
        "is unchanged (\\texttt{results/matched\\_pairs.json}).}",
        "\\label{tab:agentdojo}",
        "\\begin{tabular}{lrrrrr}", "\\toprule",
        "Configuration & Utility (\\%) & Utility under attack (\\%) & Attack success (\\%) $\\downarrow$ & Pairs & Needs a person \\\\",
        "\\midrule",
    ]
    best_asr = min((agg[c]["asr"][0] / agg[c]["asr"][1]) for c, _ in ROWS if agg[c]["asr"][1])
    for cfg, label in ROWS:
        a = agg[cfg]
        if not (a["u"][1] or a["asr"][1]):
            continue
        if cfg == "aegis_rules":
            lines.append("\\midrule")
        held, n = needs_person(cfg)
        np_cell = f"{held}/{n}" if n else "---"
        is_best = a["asr"][1] and abs(a["asr"][0] / a["asr"][1] - best_asr) < 1e-9
        pairs = str(a["asr"][1]) if a["asr"][1] else "---"
        ua = cell(*a["ua"]) if a["asr"][1] else "\\multicolumn{2}{c}{\\emph{not run: API credit}}"
        asr = cell(*a["asr"], bold=is_best) if a["asr"][1] else None
        mid = f"{ua} & {asr}" if asr else ua
        lines.append(f"{label} & {cell(*a['u'])} & {mid} & {pairs} & {np_cell} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)
    summary = {cfg: {k: {"num": v[0], "den": v[1]} for k, v in d.items()} for cfg, d in agg.items()}
    for cfg, _ in ROWS:
        summary.setdefault(cfg, {})["needs_person"] = dict(zip(("held", "of"), needs_person(cfg)))
    (RES / "summary.json").write_text(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
