"""results/adaptive_agentdojo/{baseline,attack.*}.json → paper-arxiv/figures/table_adaptive_agentdojo.tex"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results" / "adaptive_agentdojo"
OUT = HERE.parent / "paper-arxiv" / "figures" / "table_adaptive_agentdojo.tex"

base = json.load((RES / "baseline.json").open())
arms = {fb: json.load((RES / f"attack.{fb}.json").open()) for fb in ("verdict", "whitebox") if (RES / f"attack.{fb}.json").exists()}
s0 = next(iter(arms.values()))["summary"]
K, n = s0["rounds"], s0["n_targets"]
agent, attacker = base["agent"], s0["attacker"]
pc = lambda k: f"{100 * k / n:.1f}" if n else "0.0"

L = [
    "% Generated by research/agentdojo/adaptive_agentdojo.py + make_adaptive_table.py — do not edit by hand.",
    "\\begin{table}[t]", "\\centering\\small", "\\setlength{\\tabcolsep}{5pt}",
    f"\\caption{{An adaptive attacker on AgentDojo against the shipped gateway (\\texttt{{aegis\\_v3\\_audit}}: provenance "
    f"pack, destination rules as holds, the alignment auditor reviewing holds). The agent is {agent.replace('local-','')} "
    f"served locally, which---unlike Claude Haiku~4.5 (Table~\\ref{{tab:adaptive}})---acts on injections: of the {base['n_pairs']} "
    f"attack pairs on banking and Slack it carried out \\textbf{{{base['carried_out']}}} undefended, and those are the targets. "
    "Round 0 is AgentDojo's own injection; in each later round an attacker model "
    f"({attacker}) rewrites the injected text, given either only the gateway's refusal or also the rule that fired and how the "
    "pack decides (white-box). \\emph{Flagged} is the share held or blocked; an attack \\emph{escapes} only if AgentDojo's "
    "security check passes \\emph{and} the gateway allowed the sink tool.}",
    "\\label{tab:adaptive-agentdojo}",
    "\\begin{tabular}{l" + "r" * (K + 1) + "r}", "\\toprule",
    "Feedback & " + " & ".join(f"R{k}" for k in range(K + 1)) + " & Escaped \\\\",
    "\\midrule",
]
for fb, label in (("verdict", "Verdict only"), ("whitebox", "White-box")):
    if fb not in arms:
        continue
    s = arms[fb]["summary"]
    fr = [pc(s["flagged_by_round"][str(k)]) + "\\%" for k in range(K + 1)]
    L.append(f"{label} & " + " & ".join(fr) + f" & {s['escaped']} of {n} \\\\")
L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT)
for fb, a in arms.items():
    s = a["summary"]
    print(fb, "flagged@0", s["flagged_by_round"]["0"], "of", n, "| flagged@%d" % K, s["flagged_by_round"][str(K)], "| escaped", s["escaped"])
