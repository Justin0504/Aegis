import json, math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parent / "paper-arxiv" / "figures" / "table_agentdojo_qwen.tex"


def wil(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def load(p):
    d = {}
    for l in open(p):
        r = json.loads(l)
        if "error" not in r:
            d[(r["cfg"], r["suite"], r["user_task"], r.get("injection_task"))] = r
    return d


def cell(k, n):
    if not n:
        return "\\multicolumn{1}{c}{---}"
    lo, hi = wil(k, n)
    return f"{100*k/n:.1f} {{\\scriptsize[{max(0.0, 100*lo):.0f},{min(100.0, 100*hi):.0f}]}} ({k}/{n})"


def main():
    U = load(RES / "rows-utility-qwen3.jsonl"); S = load(RES / "rows-security-qwen3.jsonl")
    rows = [("none", "No defense"), ("aegis_v2", "\\system{} + L$_\\mathrm{p}$, holds refused"),
            ("aegis_v2_audit", "\\quad holds reviewed by L3")]
    L = ["% Generated by research/agentdojo/make_table_qwen.py — do not edit by hand.",
         "\\begin{table}[t]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
         "\\caption{Second agent model: qwen3:8b served locally (Ollama, reasoning off), AgentDojo banking and Slack suites "
         "(37 user tasks, 249 attack pairs). The auditor is the same local model. This run used the gateway with the destination rule "
         "of \\S\\ref{sec:authority}; the gpt-4o-mini runs of Table~\\ref{tab:agentdojo} predate it. "
         "\\system{} with holds refused was run for utility only.}",
         "\\label{tab:agentdojo-qwen}", "\\begin{tabular}{lrrr}", "\\toprule",
         "Configuration & Utility (\\%) & Util.\\ under attack (\\%) & Attack success (\\%) \\\\", "\\midrule"]
    summ = {}
    for c, label in rows:
        u = [r for k, r in U.items() if k[0] == c and k[1] in ("banking", "slack")]
        s = [r for k, r in S.items() if k[0] == c]
        uk = sum(r["utility"] for r in u); ak = sum(r["utility"] for r in s); sk = sum(r["security"] for r in s)
        summ[c] = {"utility": [uk, len(u)], "util_attack": [ak, len(s)], "asr": [sk, len(s)]}
        L.append(f"{label} & {cell(uk, len(u))} & {cell(ak, len(s))} & {cell(sk, len(s))} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    OUT.write_text("\n".join(L) + "\n")
    (RES / "summary-qwen3.json").write_text(json.dumps(summ, indent=1))
    print("wrote", OUT, json.dumps(summ))


if __name__ == "__main__":
    main()
